"""Collects REAL execution statistics for the report after the final run.

usage (from this folder, DWH_* env vars or prompts as in main.py):
    python collect_report_stats.py
Writes run_statistics.md next to this file.  Paste its sections into project_report.md.
Nothing here is invented: counts come from Data/prepare_stats.json (written by the preparation step)
and from the database tables.
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "Mesh-Join"))
import database as db                                        # noqa: E402

creds = db.prompt_credentials()
conn = db.connect(creds, autocommit=True)
cur = conn.cursor()
stats_file = HERE.parent / "Data" / "prepare_stats.json"
st = json.loads(stats_file.read_text()) if stats_file.exists() else {}


def q(sql):
    cur.execute(sql)
    return cur.fetchall()


def table(headers, rows):
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join(["---"] * len(headers)) + "|"]
    out += ["| " + " | ".join(str(x) for x in r) + " |" for r in rows]
    return "\n".join(out)


md = ["# Run statistics (generated by collect_report_stats.py)\n"]
if st:
    md.append("## Cleaning\n")
    md.append(table(["Measure", "Value"], [
        ["Transactions before the cleaning tests", f"{st['records_before_cleaning']:,}"],
        ["Transactions after the cleaning tests", f"{st['records_after_cleaning']:,}"],
        ["Removed in total", f"{st['records_removed_total']:,}"],
        ["Rule hits (overlapping): quantity <= 0", f"{st['removed_quantity_not_positive']:,}"],
        ["Rule hits: unit price <= 0", f"{st['removed_unit_price_not_positive']:,}"],
        ["Rule hits: missing customer id", f"{st['removed_missing_customer_id']:,}"],
        ["Rule hits: cancellations (C...)", f"{st['removed_cancellations']:,}"]]))
    md.append("\n## sales_mode split (MD5 rule)\n")
    md.append(table(["Form", "Transactions", "Share"], [
        ["Online", f"{st['online_transactions']:,}", f"{st['online_share_pct']} %"],
        ["Periodic", f"{st['periodic_transactions']:,}", f"{round(100 - st['online_share_pct'], 2)} %"]]))
    md.append("\n## Master Data and periodic groups\n")
    md.append(table(["Measure", "Value"], [
        ["Customer Master Data tuples / pages of 500", f"{st['customer_master_tuples']:,} / {st['customer_master_pages']}"],
        ["Product Master Data tuples / pages of 500", f"{st['product_master_tuples']:,} / {st['product_master_pages']}"],
        ["Periodic groups", st["periodic_groups"]],
        ["Smallest group", f"{st['periodic_group_min']:,}"], ["Largest group", f"{st['periodic_group_max']:,}"],
        ["Dates in the cleaned file", f"{st['first_event_time']} .. {st['last_event_time']}"]]))

md.append("\n## Data warehouse content\n")
md.append(table(["Table", "Rows"], [[t, f"{q(f'SELECT COUNT(*) FROM {t}')[0][0]:,}"] for t in
                                    ["fact_sales", "dim_customer", "dim_product", "dim_supplier", "dim_store", "dim_time"]]))
md.append("\nfact_sales by sales_mode and processing_mode:\n")
md.append(table(["sales_mode", "processing_mode", "rows"], q(
    "SELECT sales_mode, processing_mode, FORMAT(COUNT(*),0) FROM fact_sales GROUP BY 1,2 ORDER BY 1,2")))
md.append("\nLoaded dates: " + " .. ".join(str(x) for x in q("SELECT MIN(date_value), MAX(date_value) FROM dim_time")[0]))

md.append("\n## Load shedding\n")


def shed_count(speed):
    return q("SELECT COUNT(*) FROM shed_table WHERE shed_speed = '" + speed + "'")[0][0]


replayed = q("SELECT COALESCE(SUM(replayed), 0) FROM shed_table")[0][0]
on_disk = q("SELECT COUNT(*) FROM shed_table WHERE replayed = 0")[0][0]
md.append(table(["Measure", "Transactions"], [
    ["Shed to disk during PEAK", f"{shed_count('peak'):,}"],
    ["Shed to disk during NON-PEAK (shedding is not allowed there)", f"{shed_count('non-peak'):,}"],
    ["Shed at shutdown (kept safe, not load related)", f"{shed_count('shutdown'):,}"],
    ["Replayed (processed) afterwards", f"{int(replayed):,}"],
    ["Still on the shed disk", f"{on_disk:,}"]]))
md.append("\nShed rows per simulated hour group is visible in shed_table.shed_time / event_time.")
md.append("\n## Bonus cache\n")
md.append(f"Rows left in live_sales_cache: {q('SELECT COUNT(*) FROM live_sales_cache')[0][0]:,}")

md.append("\n## Q19 spike facts (for the written comment)\n")
spikes = q("""WITH daily AS (SELECT f.product_key, t.date_value, SUM(f.revenue) r FROM fact_sales f
              JOIN dim_time t ON t.time_key=f.time_key GROUP BY 1,2),
              d AS (SELECT daily.*, AVG(r) OVER (PARTITION BY product_key) a FROM daily)
              SELECT COUNT(*), COUNT(DISTINCT product_key), COUNT(DISTINCT date_value) FROM d WHERE r > 2*a""")[0]
md.append(f"Spike rows: {spikes[0]:,} over {spikes[1]:,} products and {spikes[2]:,} distinct days.\n")
md.append("Days with the most simultaneously spiking products:\n")
md.append(table(["date", "products spiking", "spike revenue"], q("""
    WITH daily AS (SELECT f.product_key, t.date_value, SUM(f.revenue) r FROM fact_sales f
                   JOIN dim_time t ON t.time_key=f.time_key GROUP BY 1,2),
         d AS (SELECT daily.*, AVG(r) OVER (PARTITION BY product_key) a FROM daily)
    SELECT date_value, COUNT(*), ROUND(SUM(r),2) FROM d WHERE r > 2*a GROUP BY date_value
    ORDER BY 2 DESC LIMIT 8""")))
md.append("\nMonth of the largest spike rows:\n")
md.append(table(["year", "month", "spike rows"], q("""
    WITH daily AS (SELECT f.product_key, t.date_value, t.year_num y, t.month_num m, SUM(f.revenue) r
                   FROM fact_sales f JOIN dim_time t ON t.time_key=f.time_key GROUP BY 1,2,3,4),
         d AS (SELECT daily.*, AVG(r) OVER (PARTITION BY product_key) a FROM daily)
    SELECT y, m, COUNT(*) FROM d WHERE r > 2*a GROUP BY y, m ORDER BY 3 DESC LIMIT 5""")))

(HERE / "run_statistics.md").write_text("\n".join(md) + "\n", encoding="utf-8")
print("written", HERE / "run_statistics.md")
